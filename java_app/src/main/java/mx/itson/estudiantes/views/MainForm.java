    // Pide el listado a la API y llena la tabla
    public void cargar() {
        try {
            estudiantes = api.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblEstudiantes.getModel();
            modelo.setRowCount(0);
            for (Estudiante e : estudiantes) {
                modelo.addRow(new Object[]{
                    e.getId(), e.getNombre(), e.getMatricula(),
                    e.getCarrera(), e.getSemestre(), e.getCorreo()
                });
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

