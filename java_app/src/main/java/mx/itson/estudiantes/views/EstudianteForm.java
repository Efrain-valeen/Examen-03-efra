    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Campos obligatorios
        if (txtNombre.getText().isBlank() || txtMatricula.getText().isBlank()
                || txtCarrera.getText().isBlank() || txtSemestre.getText().isBlank()
                || txtCorreo.getText().isBlank()) {
            JOptionPane.showMessageDialog(this, "Completa todos los campos");
            return;
        }
        try {
            Estudiante e = (estudiante == null) ? new Estudiante() : estudiante;
            e.setNombre(txtNombre.getText().trim());
            e.setMatricula(txtMatricula.getText().trim());
            e.setCarrera(txtCarrera.getText().trim());
            e.setSemestre(Integer.parseInt(txtSemestre.getText().trim()));
            e.setCorreo(txtCorreo.getText().trim());

            api.guardar(e); // POST si es nuevo, PUT si es edición
            lista.cargar();
            dispose();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El semestre debe ser un número");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

